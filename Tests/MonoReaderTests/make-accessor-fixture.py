#!/usr/bin/env python3
"""Regenerates AccessorCodeFixture.swift from a Hearthstone install.

The fixture holds the machine code of the Mono accessor functions MonoLayout reads its offsets from, for both the
arm64 and x86_64 slices of Hearthstone's libmonobdwgc-2.0.dylib (Mono is MIT-licensed). Tests run the real
decoding on the real instructions of both CPU types without Hearthstone.

Usage: python3 -I Tests/MonoReaderTests/make-accessor-fixture.py \
         [/Applications/Hearthstone/Hearthstone.app/Contents/Frameworks/libmonobdwgc-2.0.dylib]
"""
import pathlib
import struct
import sys

SYMBOLS = [
    "_mono_get_root_domain",
    "_mono_assembly_get_name", "_mono_assembly_get_image", "_mono_class_get_element_class", "_mono_class_get_flags",
    "_mono_class_is_valuetype", "_mono_class_get_parent", "_mono_class_get_nesting_type", "_mono_class_get_image",
    "_mono_class_get_name", "_mono_class_get_namespace", "_mono_array_element_size", "_mono_class_get_fields",
    "_mono_class_get_type", "_mono_field_get_type", "_mono_field_get_name", "_mono_field_get_offset",
    "_mono_type_get_type", "_mono_string_length", "_mono_string_chars", "_mono_array_length",
    "_mono_array_addr_with_size", "_mono_vtable_get_static_field_data",
]
WINDOW = 256
CPU = {0x0100000C: "arm64", 0x01000007: "x86_64"}


def slices(data):
    magic = struct.unpack(">I", data[:4])[0]
    if magic != 0xCAFEBABE:
        raise SystemExit("not a universal binary")
    count = struct.unpack(">I", data[4:8])[0]
    for index in range(count):
        cputype, _, offset, size, _ = struct.unpack(">iiIII", data[8 + index * 20: 28 + index * 20])
        yield CPU.get(cputype & 0xFFFFFFFF), data[offset: offset + size]


def parse(macho):
    ncmds = struct.unpack("<I", macho[16:20])[0]
    cursor = 32
    text = symtab = None
    for _ in range(ncmds):
        cmd, size = struct.unpack("<II", macho[cursor: cursor + 8])
        if cmd == 0x19 and macho[cursor + 8: cursor + 24].rstrip(b"\0") == b"__TEXT":
            vmaddr, _, fileoff = struct.unpack("<QQQ", macho[cursor + 24: cursor + 48])
            text = (vmaddr, fileoff)
        elif cmd == 0x2:
            symtab = struct.unpack("<IIII", macho[cursor + 8: cursor + 24])
        cursor += size
    symoff, nsyms, stroff, _ = symtab
    found = {}
    for index in range(nsyms):
        strx, ntype, _, _, value = struct.unpack("<IBBHQ", macho[symoff + index * 16: symoff + index * 16 + 16])
        if ntype & 0xE0 or ntype & 0x0E != 0x0E:
            continue
        end = macho.index(b"\0", stroff + strx)
        name = macho[stroff + strx: end].decode()
        if name in SYMBOLS:
            found[name] = value
    return text, found


def main():
    path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                        "/Applications/Hearthstone/Hearthstone.app/Contents/Frameworks/libmonobdwgc-2.0.dylib")
    data = path.read_bytes()
    out = [
        "// Generated by make-accessor-fixture.py from Hearthstone 37.0's libmonobdwgc-2.0.dylib (Unity 6000.3.11f1).",
        "// Machine code of Mono's (MIT-licensed) accessor functions, in both CPU slices. Do not edit by hand.",
        "",
        "enum AccessorCodeFixture {",
        "  struct Chunk {",
        "    let symbol: String",
        "    /// Address relative to the image's __TEXT start.",
        "    let address: UInt64",
        "    let hex: String",
        "  }",
        "",
    ]
    for arch, macho in slices(data):
        (vmaddr, fileoff), symbols = parse(macho)
        missing = set(SYMBOLS) - set(symbols)
        if missing:
            raise SystemExit(f"{arch}: missing {sorted(missing)}")
        out.append(f"  static let {arch}: [Chunk] = [")
        for name in SYMBOLS:
            relative = symbols[name] - vmaddr
            start = fileoff + relative
            out.append(f'    Chunk(symbol: "{name}", address: 0x{relative:x}, hex: "{macho[start:start + WINDOW].hex()}"),')
        out.append("  ]")
        out.append("")
    out.append("}")
    target = pathlib.Path(__file__).with_name("AccessorCodeFixture.swift")
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target}")


main()
